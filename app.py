"""Gradio app: generate realistic human faces with the GAN models trained on Kaggle.

Run locally:      python app.py            (opens on http://localhost:7860)
Environment:      PORT / GRADIO_SERVER_PORT   port to listen on (default 7860)
                  GRADIO_SERVER_NAME          host to bind (default 0.0.0.0)
                  GRADIO_SHARE=1              also create a temporary public gradio.live link
                  MODELS_DIR                  folder with the *.pth checkpoints (default ./models)

Inference runs on the CPU, so no GPU is needed.
"""

import os
from pathlib import Path

import gradio as gr

from gan_faces import discover_models, generate_faces, load_generator, tensor_to_pil

MODELS_DIR = Path(os.getenv("MODELS_DIR", Path(__file__).parent / "models"))
MODELS = discover_models(MODELS_DIR)
if not MODELS:
    raise SystemExit(
        f"No checkpoints found in '{MODELS_DIR}'. Download DCGAN_best.pth and LSGAN_best.pth "
        "from the Kaggle output (/kaggle/working/models) and put them in the models/ folder."
    )

BEST_NAME = min(MODELS, key=lambda name: MODELS[name]["metric"])
BEST_LABEL = f"Best overall ({BEST_NAME})"
CHOICES = [BEST_LABEL] + list(MODELS)
CACHE = {}


def get_generator(choice):
    """Load a model once and keep it in memory."""
    name = BEST_NAME if choice == BEST_LABEL else choice
    if name not in CACHE:
        CACHE[name] = load_generator(MODELS[name]["path"], map_location="cpu")
    return CACHE[name]


def generate_for_ui(model_choice, n_images, seed, randomize):
    G, ckpt = get_generator(model_choice)
    faces = generate_faces(G, int(n_images), seed=None if randomize else int(seed))
    images = [tensor_to_pil(face, size=256) for face in faces]
    info = (f"Model: {ckpt['name']} | loss: {ckpt.get('loss_type', 'n/a')} | best epoch: {ckpt['epoch']} | "
            f"quality metric (lower is better): {ckpt['metric']:.4f}")
    return images, info


def models_table():
    rows = ["| Model | Loss | Best epoch | Quality metric (lower is better) |", "|---|---|---|---|"]
    for name, info in MODELS.items():
        rows.append(f"| {name}{' (best)' if name == BEST_NAME else ''} | {info['loss_type']} | {info['epoch']} | {info['metric']:.4f} |")
    return "\n".join(rows)


with gr.Blocks(title="GAN Face Generator") as demo:
    gr.Markdown(
        "# Realistic Human Face Generation using GAN\n"
        "Choose a model, then generate synthetic 64x64 faces from random noise. "
        "The faces are generated by a Generator trained on a CelebA subset; they are not real people.\n\n"
        + models_table()
    )
    with gr.Row():
        with gr.Column(scale=1):
            model_dd = gr.Dropdown(choices=CHOICES, value=BEST_LABEL, label="Model")
            n_slider = gr.Slider(1, 16, value=8, step=1, label="Number of faces")
            seed_box = gr.Number(value=42, precision=0, label="Seed")
            random_cb = gr.Checkbox(value=True, label="Random seed (new faces every click)")
            run_btn = gr.Button("Generate faces", variant="primary")
            info_box = gr.Textbox(label="Model info", interactive=False)
        with gr.Column(scale=2):
            gallery = gr.Gallery(label="Generated faces", columns=4, height="auto")
    run_btn.click(generate_for_ui, inputs=[model_dd, n_slider, seed_box, random_cb], outputs=[gallery, info_box])


if __name__ == "__main__":
    demo.launch(
        server_name=os.getenv("GRADIO_SERVER_NAME", "0.0.0.0"),
        server_port=int(os.getenv("PORT", os.getenv("GRADIO_SERVER_PORT", "7860"))),
        share=os.getenv("GRADIO_SHARE", "0") == "1",
    )
